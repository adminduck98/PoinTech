-- ============================================================
-- Фото отзывов и возвратов — в закрытые бакеты.
--
-- Оба содержат снимки, которые присылает покупатель: дефект товара в заявке на
-- возврат, фото к отзыву. Пока бакет открыт, любой обладатель ссылки открывает
-- файл напрямую, минуя приложение. Ссылки теперь со случайным UUID, то есть не
-- подбираются, но однажды утёкшая ссылка остаётся рабочей навсегда.
--
-- После этой миграции прямой доступ закрыт. Показ идёт по подписанной ссылке
-- на час, которую выдаёт edge-функция уже после проверки вызывающего:
--
--   client-api  get_product_reviews  → фото отзывов на карточке товара
--   client-api  get_user_returns     → возвраты самого покупателя
--   admin-api   select reviews/returns → админ-панель
--
-- В базе с этого момента хранится ПУТЬ внутри бакета, а не ссылка
-- (см. _shared/storage.ts). Строки со старыми полными ссылками функция
-- пропускает как есть, так что ранее сохранённые данные не ломаются.
--
-- Фото товаров и баннеры остаются открытыми: это витрина, её видят все.
-- ============================================================

UPDATE storage.buckets SET public = false WHERE id IN ('review-photos', 'return-photos');

DO $$
DECLARE
  row_ record;
BEGIN
  FOR row_ IN SELECT id, public FROM storage.buckets ORDER BY id LOOP
    RAISE NOTICE 'бакет % — %', row_.id, CASE WHEN row_.public THEN 'открытый' ELSE 'закрытый' END;
  END LOOP;
END
$$;
