-- ============================================================
-- products.specs: jsonb → json, чтобы характеристики шли в том порядке,
-- в каком их ввёл администратор.
--
-- jsonb хранит объект нормализованным и сортирует ключи по длине, затем
-- побайтово. Введённые «Объём бака, Тип, Гарантия» на карточке товара
-- превращались в «Тип, Гарантия, Объём бака» — порядок строк в таблице
-- характеристик задавала длина слова, а не смысл.
--
-- json хранит текст как есть, порядок ключей сохраняется. Ничего, кроме
-- определения колонки, к specs не обращается: в SQL-функциях и edge-функциях
-- этого поля нет, jsonb-операторы (@>, ?) к нему не применяются, а приложение
-- читает его как обычный объект. Единственное, что теряется, — индексируемость
-- по содержимому, которой здесь всё равно не было.
--
-- Уже сохранённые значения приводятся к json как есть: их порядок был потерян
-- ещё при записи, восстановить его неоткуда, но и ломаться нечему.
-- ============================================================

ALTER TABLE public.products
  ALTER COLUMN specs TYPE json USING specs::text::json;

ALTER TABLE public.products
  ALTER COLUMN specs SET DEFAULT '{}'::json;

DO $$
DECLARE
  t text;
BEGIN
  SELECT data_type INTO t
  FROM information_schema.columns
  WHERE table_schema = 'public' AND table_name = 'products' AND column_name = 'specs';

  RAISE NOTICE 'products.specs теперь %', t;
END
$$;
